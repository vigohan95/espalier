#!/usr/bin/env python3
"""Reads account-age and code-change signals for real mainnet accounts. Read-only: view calls only,
no key, no transaction. Writes docs/evidence/mainnet-signals.json and .md.

    python3 scripts/mainnet-signals.py wrap.near intents.near v2.ref-finance.near

History and denylist need a vault and a registry, and neither exists on mainnet, so here they are set
to neutral stand-ins and the verdict shows what age and code change alone produce. A signal describes
what was observed on chain. It says nothing about whether an account is good or bad."""
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "client"))

from espalier import near, policy, signals  # noqa: E402

RPC = os.environ.get("NEAR_MAINNET_RPC", "https://rpc.mainnet.fastnear.com")
ARCHIVAL = os.environ.get("NEAR_MAINNET_ARCHIVAL", "https://archival-rpc.mainnet.fastnear.com")
NEUTRAL_DENYLIST = {"listed": False, "trusted_reports": 0, "distinct_evidence": 0, "all_reports": 0, "responded": False}
NEUTRAL_HISTORY = {"agent": {"count": 10, "total": "1000", "first_ms": 0, "last_ms": 864_000_000}, "tree": None}


class Paced(near.Rpc):
    """Public archival nodes rate-limit anonymous reads, so this stays polite."""

    def raw(self, method, params, timeout=40):
        time.sleep(0.25)
        return super().raw(method, params, timeout)


def days(secs):
    return None if secs is None else round(secs / 86_400, 2)


def main():
    accounts = sys.argv[1:]
    if not accounts:
        sys.exit("usage: mainnet-signals.py ACCOUNT...")
    rpc, arc = near.Rpc(RPC), Paced(ARCHIVAL)
    started = time.time()
    rows = []
    for account in accounts:
        s = signals.gather(rpc, arc, account)
        decided = policy.decide({**s, "denylist": NEUTRAL_DENYLIST, "history": NEUTRAL_HISTORY}, 100, policy.Policy())
        rows.append({"signals": s, "verdict_from_age_and_code_only": decided})
        code = s.get("code") or {}
        print(
            f"{account}: {decided['verdict']}; age {days((s.get('age') or {}).get('age_secs'))} days, "
            f"contract {s.get('is_contract')}, code {s.get('code_hash')}, changed {days(code.get('changed_ago_secs'))} days ago "
            f"(block {code.get('changed_block')}), full-access keys {(s.get('keys') or {}).get('full_access_keys')}",
            flush=True,
        )
    doc = {
        "what": "read-only mainnet queries; signals are observations, not accusations",
        "queried_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "rpc": RPC,
        "archival_rpc": ARCHIVAL,
        "rpc_methods": ["query view_account (at final and at past block heights)", "query view_access_key_list", "block"],
        "archival_reads": arc.calls,
        "seconds": round(time.time() - started, 1),
        "policy": {"young_days": 7, "code_change_days": 7},
        "stand_ins": "history and denylist are neutral stand-ins here: no vault or registry exists on mainnet",
        "accounts": rows,
    }
    out = os.path.join(HERE, "..", "docs", "evidence", "mainnet-signals")
    json.dump(doc, open(out + ".json", "w"), indent=2)
    with open(out + ".md", "w") as f:
        f.write("# Recipient signals on real mainnet accounts\n\n")
        f.write(f"Generated by `scripts/mainnet-signals.py` at {doc['queried_at']}, read-only, from `{RPC}` and `{ARCHIVAL}`. ")
        f.write(f"{arc.calls} archival reads. No key and no transaction was involved. Each value can be checked with `view_account` at the block shown.\n\n")
        f.write("A signal is an observation. A recent code change is what a normal upgrade looks like too, and `warn` only means a person takes a look. Nothing here says any account did anything wrong.\n\n")
        f.write("| Account | First seen at block | Age (days) | Contract | Last code change at block | Changed (days ago) | Code hash before | Code hash now | Full-access keys | Verdict from these signals |\n|---|---|---|---|---|---|---|---|---|---|\n")
        for r in rows:
            s = r["signals"]
            a, c, k = s.get("age") or {}, s.get("code") or {}, s.get("keys") or {}
            f.write(
                f"| `{s['account']}` | {a.get('created_block')} | {days(a.get('age_secs'))} | {s.get('is_contract')} | {c.get('changed_block')} | "
                f"{days(c.get('changed_ago_secs'))} | `{(c.get('previous_code_hash') or '-')[:10]}` | `{(s.get('code_hash') or '-')[:10]}` | "
                f"{k.get('full_access_keys')} | {r['verdict_from_age_and_code_only']['verdict']} |\n"
            )
        f.write("\nReasons:\n\n")
        for r in rows:
            reasons = [x for x in r["verdict_from_age_and_code_only"]["reasons"] if x["code"] != "KNOWN_RECIPIENT"]
            f.write(f"- `{r['signals']['account']}`: " + ("; ".join(f"{x['code']} ({x['detail']})" for x in reasons) or "none") + "\n")
        f.write(f"\n{doc['stand_ins']}. How age and code history are found, and the limits of the method: `client/espalier/signals.py`.\n")


main()
