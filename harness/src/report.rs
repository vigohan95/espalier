//! Evidence reports: one JSON for machines, one Markdown table for people.
use crate::env::{Fact, Trace, TxRecord};
use crate::scenarios::Scenario;
use anyhow::Result;
use serde::Serialize;
use serde_json::json;
use std::process::Command;

#[derive(Clone, Debug, Serialize)]
pub struct ScenarioResult {
    pub id: String,
    pub group: String,
    pub title: String,
    pub status: String,
    pub error: String,
    pub seconds: f64,
    pub facts: Vec<Fact>,
    pub txs: Vec<TxRecord>,
}

impl ScenarioResult {
    pub fn new(s: &Scenario, status: String, error: String, seconds: f64, trace: &Trace) -> Self {
        Self {
            id: s.id.to_string(),
            group: s.group.to_string(),
            title: s.title.to_string(),
            status,
            error,
            seconds,
            facts: trace.facts.lock().unwrap().clone(),
            txs: trace.txs.lock().unwrap().clone(),
        }
    }
}

pub fn git_commit() -> String {
    Command::new("git")
        .args(["rev-parse", "--short", "HEAD"])
        .output()
        .ok()
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
        .unwrap_or_default()
}

pub fn wasm_sha256() -> String {
    Command::new("sha256sum")
        .arg(crate::wasm_path("espalier_vault"))
        .output()
        .ok()
        .map(|o| String::from_utf8_lossy(&o.stdout).split_whitespace().next().unwrap_or("").to_string())
        .unwrap_or_default()
}

pub fn write_report(path: Option<&str>, network: &str, version: &str, seconds: f64, results: &[ScenarioResult]) -> Result<bool> {
    let pass = results.iter().filter(|r| r.status == "pass").count();
    let facts: usize = results.iter().map(|r| r.facts.len()).sum();
    let txs: usize = results.iter().map(|r| r.txs.len()).sum();
    println!("\n{pass}/{} scenarios passed, {facts} assertions, {txs} recorded transactions, {seconds:.0}s", results.len());
    if let Some(p) = path {
        let doc = json!({
            "network": network,
            "node_version": version,
            "wasm_sha256": wasm_sha256(),
            "git_commit": git_commit(),
            "seconds": seconds,
            "passed": pass,
            "total": results.len(),
            "assertions": facts,
            "scenarios": results,
        });
        std::fs::write(format!("{p}.json"), serde_json::to_string_pretty(&doc)?)?;
        let mut md = format!(
            "# Scenario report ({network})\n\nGenerated by `harness`. Do not edit by hand.\n\n- Node: `{version}`\n- Contract wasm sha256: `{}`\n- Commit: `{}`\n- Result: **{pass}/{} scenarios passed**, {facts} assertions\n\n| ID | Group | Scenario | Result | Assertions | Reason codes seen |\n|---|---|---|---|---|---|\n",
            wasm_sha256(),
            git_commit(),
            results.len()
        );
        for r in results {
            let mut codes: Vec<&str> = r.txs.iter().map(|t| t.code.as_str()).filter(|c| !c.is_empty() && *c != "GRANTED").collect();
            codes.sort();
            codes.dedup();
            md.push_str(&format!(
                "| {} | {} | {} | {} | {} | {} |\n",
                r.id,
                r.group,
                r.title,
                r.status,
                r.facts.len(),
                codes.join(", ")
            ));
        }
        std::fs::write(format!("{p}.md"), md)?;
    }
    Ok(pass == results.len())
}
